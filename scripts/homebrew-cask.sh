#!/usr/bin/env bash
# Write the tap's casks for a release: Casks/trunk.rb, and the pinned
# trunk@<version>.rb that the same tag serves.
#
#   homebrew-cask.sh <tag> <tauri-version> <intel-sha256> <arm-sha256> <casks-dir>
set -euo pipefail

tag=$1
tauri_version=$2
intel_sha256=$3
arm_sha256=$4
casks=$5
version="${tag#v}"

# Both versions land inside Ruby strings in the cask, where `#{...}` runs as
# code on every machine that reads it.
release='^[0-9]+\.[0-9]+\.[0-9]+$'
if ! [[ "$version" =~ $release && "$tauri_version" =~ $release ]]; then
  echo "::error::cask versions must be MAJOR.MINOR.PATCH: tag $tag, tauri.conf.json $tauri_version" >&2
  exit 1
fi

# The cask body is identical for both files apart from the token, so write it
# once through a function. A versioned cask whose contents drift from the
# unversioned one would install something different from what the same tag
# serves as latest.
write_cask() {
  cat > "$1" << CASK
# Generated by joaofnds/trunk release workflow. DO NOT EDIT.
cask "$2" do
  version "${version}"

  on_intel do
    sha256 "${intel_sha256}"
    url "https://github.com/joaofnds/trunk/releases/download/v${version}/Trunk_${tauri_version}_x64.dmg"
  end
  on_arm do
    sha256 "${arm_sha256}"
    url "https://github.com/joaofnds/trunk/releases/download/v${version}/Trunk_${tauri_version}_aarch64.dmg"
  end

  name "Trunk"
  desc "Desktop Git GUI"
  homepage "https://github.com/joaofnds/trunk"

  depends_on macos: :ventura

  app "Trunk.app"
  binary "#{appdir}/Trunk.app/Contents/MacOS/trunk"

  postflight_steps do
    run "/usr/bin/xattr", args: ["-cr", "{{appdir}}/Trunk.app"]
  end

  zap trash: [
    "~/Library/Application Support/com.joaofnds.trunk",
    "~/Library/Caches/com.joaofnds.trunk",
    "~/Library/WebKit/com.joaofnds.trunk",
  ]
end
CASK
}

# brew resolves `trunk@0.45.0` to Casks/trunk@0.45.0.rb, so the token inside
# the file has to carry the version too or the name it is installed by will
# not match the name it declares.
write_cask "$casks/trunk.rb" trunk
write_cask "$casks/trunk@${version}.rb" "trunk@${version}"
